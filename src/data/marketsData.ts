function seededHash(str: string): number {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

export function generateChartSeries(
  instrument: MarketInstrument,
  timeframe: Timeframe
): OhlcPoint[] {
  const counts: Record<Timeframe, number> = {
    '1D': 48,
    '5D': 52,
    '1M': 44,
    '6M': 56,
    YTD: 60,
    '1Y': 64,
    '5Y': 60,
    ALL: 64,
  };

  const volatilityMap: Record<Timeframe, number> = {
    '1D': 0.0018,
    '5D': 0.0042,
    '1M': 0.0085,
    '6M': 0.015,
    YTD: 0.017,
    '1Y': 0.022,
    '5Y': 0.036,
    ALL: 0.045,
  };

  const count = counts[timeframe];
  const stepVol = volatilityMap[timeframe];
  let seed = seededHash(`${instrument.symbol}-${timeframe}`);

  const nextRand = () => {
    seed = (seed * 1664525 + 1013904223) >>> 0;
    return seed / 4294967296;
  };

  // Start anchor depending on timeframe
  const targetPrice = instrument.price;
  const startOffset =
    timeframe === '1D'
      ? instrument.prevClose
      : targetPrice *
        (1 -
          (instrument.changePct >= 0 ? 1 : -0.4) *
            (timeframe === '5D'
              ? 0.018
              : timeframe === '1M'
              ? 0.045
              : timeframe === '6M'
              ? 0.12
              : timeframe === 'YTD'
              ? 0.19
              : timeframe === '1Y'
              ? 0.24
              : timeframe === '5Y'
              ? 0.55
              : 0.72));

  // Generate raw random walk then bridge smoothly to exact current price
  const rawCloses: number[] = [startOffset];
  for (let i = 1; i < count; i++) {
    const prev = rawCloses[i - 1];
    const drift = (nextRand() - 0.48) * stepVol * prev;
    rawCloses.push(Math.max(prev * 0.1, prev + drift));
  }

  const rawEnd = rawCloses[count - 1];
  const bridgeDelta = targetPrice - rawEnd;

  const points: OhlcPoint[] = [];
  for (let i = 0; i < count; i++) {
    const progress = i / (count - 1);
    const close = rawCloses[i] + bridgeDelta * progress;
    const prevClose = i === 0 ? startOffset : points[i - 1].close;
    const open = i === 0 ? startOffset : prevClose;
    const wickScale = Math.abs(close) * stepVol * (0.45 + nextRand() * 0.75);
    const high = Math.max(open, close) + wickScale * nextRand();
    const low = Math.min(open, close) - wickScale * nextRand();

    let label = '';
    if (timeframe === '1D') {
      const totalMinutes = 9 * 60 + 30 + Math.round((i / (count - 1)) * 390);
      const hh = Math.floor(totalMinutes / 60);
      const mm = totalMinutes % 60;
      label = `${hh.toString().padStart(2, '0')}:${mm.toString().padStart(2, '0')}`;
    } else if (timeframe === '5D') {
      const dayNames = ['Thu', 'Fri', 'Mon', 'Tue', 'Wed'];
      const dayIdx = Math.min(4, Math.floor((i / count) * 5));
      const hr = 9 + Math.floor(((i % 10) / 10) * 7);
      label = `${dayNames[dayIdx]} ${hr}:00`;
    } else if (timeframe === '1M') {
      const day = Math.max(1, Math.round(1 + progress * 24));
      label = `Nov ${day}`;
    } else if (timeframe === '6M' || timeframe === 'YTD' || timeframe === '1Y') {
      const months = ['Dec', 'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov'];
      const mIdx = Math.min(months.length - 1, Math.floor(progress * 12));
      label = `${months[mIdx]} 2026`;
    } else {
      const yr = timeframe === '5Y' ? 2021 + Math.floor(progress * 5.9) : 2016 + Math.floor(progress * 10.9);
      const q = 1 + (i % 4);
      label = `Q${q} ${yr}`;
    }

    points.push({
      label,
      open: Number(open.toFixed(instrument.decimals)),
      high: Number(high.toFixed(instrument.decimals)),
      low: Number(low.toFixed(instrument.decimals)),
      close: Number(close.toFixed(instrument.decimals)),
      volume: Math.round(40 + nextRand() * 160),
    });
  }

  // Pin final close to exact current price
  points[points.length - 1].close = instrument.price;
  return points;
}

export function formatInstrumentPrice(price: number, decimals: number, unit?: string): string {
  const formatted = price.toLocaleString('en-US', {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  });
  return unit === '%' ? `${formatted}%` : formatted;
}
